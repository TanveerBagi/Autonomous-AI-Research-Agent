from datetime import datetime
import re

def clean_text(text: str) -> str:
    text = text.encode("latin-1", "replace").decode("latin-1")
    text = re.sub(r'\*+', '', text)
    text = re.sub(r'#+\s*', '', text)
    text = re.sub(r'-{2,}', '', text)
    return text.strip()
